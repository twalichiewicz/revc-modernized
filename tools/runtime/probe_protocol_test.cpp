#include "probe_protocol.h"
#include "probe_joints.h"
#include <cassert>
#include <cstdio>
int main() {
    auto valid = [](const char *line) { probe::Command c; std::string e; return probe::Parse(line, c, e); };
    assert(valid("1 status"));
    assert(valid("100 playerhit 10"));assert(valid("101 playerhit 0.001"));
    assert(!valid("102 playerhit 0"));assert(!valid("103 playerhit 10.001"));assert(!valid("104 playerhit nan"));assert(!valid("105 playerhit 1 extra"));
    assert(valid("106 carroll 0"));assert(valid("107 carroll 1"));assert(!valid("108 carroll 2"));assert(!valid("109 carroll 0.5"));

    assert(valid("2 camera -378 -552 36 -381 -544 20"));
    assert(valid("3 clock 23 59 1"));
    assert(valid("4 spawn -350 42 10"));
    assert(valid("5 damage 17 10 6 3"));
    assert(valid("6 weather -1"));
    assert(valid("7 frames start estate_rt_on"));
    assert(valid("8 npcpose"));
    assert(valid("9 pilotdamage 0 17 200 6 0"));
    assert(valid("10 helishot 1 tail"));
    assert(!valid("11 pilotdamage 2 17 200 6 0"));
    assert(!valid("12 helishot 0 unknown"));
    assert(valid("13 clouds 0"));
    assert(valid("14 lightmap 1 1.25"));
    assert(valid("15 gloss 0"));
    assert(valid("16 rimlight 1 0.5"));
    assert(!valid("17 clouds 2"));
    assert(!valid("18 lightmap 1 nan"));
    assert(!valid("19 gloss 1 9"));
    assert(!valid("20 rimlight -1"));
    assert(valid("21 filter 0"));
    assert(valid("22 filter 3"));
    assert(!valid("23 filter -1"));
    assert(!valid("24 filter 4"));
    assert(!valid("25 filter 1.5"));
    assert(valid("26 filter 2 0.5"));
    assert(valid("27 filter 2 0"));
    assert(!valid("28 filter 2 nan"));
    assert(!valid("29 filter 2 -1"));
    assert(!valid("30 filter 2 2.1"));
    assert(valid("31 npcrun -327 -489 12"));
    assert(!valid("32 npcrun 3000 -489 12"));
    assert(valid("33 weapon 17"));
    assert(valid("34 weapon 0"));
    assert(!valid("35 weapon 41"));
    assert(!valid("36 weapon 17.5"));
    assert(valid("37 npcshot foot_l -327 -489 12"));
    assert(valid("38 npcshot head 0 0 1"));
    assert(valid("39 npcshot hand_l 0 0 1"));
    assert(valid("40 npcshot foot_r 0 0 1"));
    assert(valid("41 npcshot chest 0 0 1"));
    assert(!valid("42 npcshot pelvis 0 0 1"));
    assert(!valid("43 npcshot foot_l 0 0 nan"));
    assert(!valid("44 npcshot head 0 0 1201"));
    assert(!valid("45 npcshot head 0 0 1 extra"));
    assert(valid("46 window status"));
    assert(valid("47 window native 0"));
    assert(valid("48 window native 1"));
    assert(!valid("49 window native 2"));
    assert(!valid("50 window native -1"));
    assert(!valid("51 window native 0.5"));
    assert(!valid("52 window status 1"));
    assert(!valid("53 window exclusive 1"));
    assert(!valid("54 window native nan"));
    assert(!valid("0 status"));
    assert(!valid("1 teleport nan 0 0"));
    assert(!valid("1 teleport 0 0 inf"));
    assert(!valid("1 teleport 2001 0 0"));
    assert(valid("1 teleport -1880 -2060 70"));
    assert(valid("1 teleport -2460 -100 70"));
    assert(valid("1 teleport 1660 -100 70"));
    assert(valid("1 teleport -100 2060 70"));
    assert(!valid("1 teleport -2500.01 0 70"));
    assert(!valid("1 teleport 1700.01 0 70"));
    assert(!valid("1 teleport 0 2100.01 70"));
    assert(!valid("1 teleport 0 -2100.01 70"));
    assert(!valid("1 spawn -2460 -100 70"));
    assert(!valid("1 clock 24 0 1"));
    assert(!valid("1 clock 1.5 0 1"));
    assert(!valid("1 damage 17 -1 0 0"));
    assert(!valid("1 damage 17 1 7 0"));
    assert(!valid("1 remove extra"));
    assert(!valid("1 frames start ../../escape"));
    assert(!valid("1 status\n2 remove"));
    assert(!valid("1 exec arbitrary"));
    uint8_t ready = 0;
    std::string error;
    assert(!probe::SetGradeReady(&ready, false, 1, error));
    assert(ready == 0);
    assert(probe::SetGradeReady(&ready, false, 0, error));
    assert(ready == 0);
    ready = 1;
    assert(probe::SetGradeReady(&ready, true, 0, error));
    assert(ready == 0);
    assert(probe::SetGradeReady(&ready, true, 1, error));
    assert(ready == 1);
    assert(!probe::SetGradeReady(nullptr, true, 1, error));
    assert(!probe::SetGradeReady(nullptr, false, 0, error));
    const uint8_t full[] = {0, 1, 2, 3};
    const uint8_t low[] = {0x80, 0x81, 0x82, 0};
    const uint8_t enough[] = {0x80, 0x81, 0x82, 0xff};
    assert(!probe::CanSpawnPed(full, 4, error));
    assert(!probe::CanSpawnPed(low, 4, error));
    assert(probe::CanSpawnPed(enough, 4, error));
    assert(!probe::CanSpawnPed(nullptr, 4, error));
    assert(!probe::CanSpawnPed(enough, 0, error));
    assert(!probe::CanSpawnPed(enough, 8193, error));
    constexpr int tags[] = {1,3,5,32,33,34,22,23,24,41,42,43,51,52,53};
    static_assert(probe::kJoints.size() == 15, "all physical joints require telemetry");
    for(size_t i=0;i<probe::kJoints.size();++i) {
        assert(size_t(probe::kJoints[i].joint)==i);
        assert(probe::kJoints[i].tag==tags[i]);
        for(size_t j=0;j<i;++j) assert(std::string(probe::kJoints[i].name)!=probe::kJoints[j].name);
    }
    std::puts("probe protocol: bounded command, grade and spawn policy checks; all 15 telemetry joints passed");
}
