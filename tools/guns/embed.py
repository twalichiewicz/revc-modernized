"""Writes the files that build the viewmodel guns into the mod: an assembly file that includes each
assets/guns/<name>.vmg, and a list of their names for src/gunassets.cpp. Each is rewritten only when it
changes.

python3 -I tools/guns/embed.py <out.S> <out list.h> assets/guns/a.vmg [...]
"""
import os
import sys

out_s, out_h, files = sys.argv[1], sys.argv[2], sorted(sys.argv[3:])
names = [os.path.splitext(os.path.basename(f))[0] for f in files]
asm = ["// Generated by tools/guns/embed.py: the viewmodel's guns, built into the mod.\n", "\t.section __DATA,__const\n"]
for name, path in zip(names, files):
    asm.append(f"\t.p2align 2\n\t.globl _vmgun_{name}, _vmgun_{name}_end\n\t.private_extern _vmgun_{name}, _vmgun_{name}_end\n")
    asm.append(f"_vmgun_{name}:\n\t.incbin \"{path}\"\n_vmgun_{name}_end:\n")
header = ["// Generated by tools/guns/embed.py: GUN(name) for each assets/guns/<name>.vmg.\n"]
header += [f"GUN({name})\n" for name in names]


def write(path, text):
    """Only when it changes, so what depends on it is only rebuilt then (make runs this every time)."""
    try:
        if open(path).read() == text:
            return
    except OSError:
        pass
    with open(path, "w") as f:
        f.write(text)


write(out_s, "".join(asm))
write(out_h, "".join(header))
